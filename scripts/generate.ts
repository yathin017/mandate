import assert from "node:assert/strict";
import { readFile, readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { join } from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const check = process.argv.includes("--check");
const header = "// Generated by scripts/generate.ts. Edit the source JSON/Solidity, then run pnpm generate.\n";
async function json(path: string) { return JSON.parse(await readFile(join(root, path), "utf8")); }
async function output(path: string, content: string) {
  if (check) {
    assert.equal(await readFile(join(root, path), "utf8"), content, `Generated file is stale: ${path}`);
  } else await writeFile(join(root, path), content);
}

const chains = [];
for (const file of (await readdir(join(root, "config/chains"))).filter((f) => /^\d+\.json$/.test(f)).sort()) {
  const config = await json(`config/chains/${file}`);
  assert.equal(config.chainId, Number(file.slice(0, -5)), `Chain id/file mismatch: ${file}`);
  chains.push(config);
}
const deployments = [];
for (const file of (await readdir(join(root, "deployments"))).filter((f) => /^\d+\.json$/.test(f)).sort()) {
  const deployment = await json(`deployments/${file}`);
  assert.equal(deployment.sourceChainId, Number(file.slice(0, -5)), `Fork source/file mismatch: ${file}`);
  deployments.push(deployment);
}
await output("packages/chains/src/generated.ts", header
  + `export const chainData = ${JSON.stringify(chains, null, 2)} as const;\n`
  + `export const deploymentData = ${JSON.stringify(deployments, null, 2)} as const;\n`);

const contracts = {
  mandateModule: "MandateModule.sol/MandateModule",
  mandateQuoter: "MandateQuoter.sol/MandateQuoter",
  uniswapV4TwapAnchor: "UniswapV4TwapAnchor.sol/UniswapV4TwapAnchor",
  mandateOracleHook: "MandateOracleHook.sol/MandateOracleHook",
  aqua: "IAqua.sol/IAqua",
  swapVm: "ISwapVM.sol/ISwapVM",
  aquaSwapVmRouter: "AquaSwapVMRouter.sol/AquaSwapVMRouter",
  safe: "SafeTransactions.sol/ISafeAccount",
  safeProxyFactory: "SafeTransactions.sol/ISafeProxyFactory",
  erc20: "IERC20.sol/IERC20",
  erc20Metadata: "IERC20Metadata.sol/IERC20Metadata",
  erc20Errors: "draft-IERC6093.sol/IERC20Errors",
  oracle: "Oracle.sol/Oracle",
  demoState: "DemoState.sol/DemoState",
  scenarioActor: "ScenarioActor.sol/ScenarioActor",
};
let abis = header + 'import type { Abi } from "viem";\n\n';
for (const [name, path] of Object.entries(contracts)) {
  const artifact = await json(`contracts/out/${path}.json`);
  assert.ok(Array.isArray(artifact.abi), `Missing ABI: ${path}`);
  // Preserve the compiler's ABI exactly, including inherited errors and tuple component names.
  abis += `// Source artifact: contracts/out/${path}.json\n`;
  abis += `export const ${name}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const satisfies Abi;\n\n`;
}
await output("packages/sdk/src/abis.ts", abis.trimEnd() + "\n");
console.log(check ? "Generated registry and ABIs are current." : "Generated registry and contract ABIs.");
